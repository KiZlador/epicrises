def messages(document: str, fields: list[str], current: dict, analysis: dict) -> list[dict]:
    groups = {g: [k for k in keys if k in fields] for g, keys in GROUPS.items()}
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": json.dumps(
                {
                    "requested_fields": fields,
                    "field_groups": {g: keys for g, keys in groups.items() if keys},
                    "current_values": {k: current[k] for k in fields},
                    "review_signals": analysis["triggered_rules"],
                    "document": document,
                },
                ensure_ascii=False,
            )
            + "\nОтвет должен содержать только поля следующего объекта. Заполни их по тексту; "
            "если упоминания нет, оставь значение по правилу отсутствия. Не возвращай входной JSON.\n"
            + json.dumps({key: current[key] for key in fields}, ensure_ascii=False),
        },
    ]


def evidence_messages(lines: list[str], values: dict, candidates: dict) -> list[dict]:
    allowed = {index for key in values for index in candidates[key]}
    numbered = "\n".join(f"{index}: {lines[index - 1]}" for index in sorted(allowed))
    return [
        {"role": "system", "content": EVIDENCE_PROMPT},
        {
            "role": "user",
            "content": "Значения для подтверждения:\n"
            + json.dumps(values, ensure_ascii=False)
            + "\nДопустимые номера для каждого поля:\n"
            + json.dumps({key: candidates[key] for key in values}, ensure_ascii=False)
            + "\nСтроки документа:\n"
            + numbered
            + "\nЗаполни объект номерами строк либо null:\n"
            + json.dumps(dict.fromkeys(values), ensure_ascii=False),
        },
    ]
